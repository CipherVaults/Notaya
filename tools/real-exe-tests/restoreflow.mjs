import { connectLegacy, closeLegacyClients, createNotebookSection } from "./legacy-cdp.mjs";
// restoreflow.mjs - real-exe test of "restore from backup" (restore_vault, list_backups).
// Purpose: creates a vault in the running test app, makes two backups (ORIGINAL and CHANGED text),
//          then checks restore while locked and unlocked, and the refusals (bad paths, wrong password).
//          Prints PASS / FAIL lines.
// Usage:   normally started by run-restoreflow.ps1:  node restoreflow.mjs <port> <password-file>
//          <port> is the WebView2 debug port (9335) of a test copy of Notaya.exe;
//          <password-file> holds the throwaway passphrase (generated by the runner, never committed).
// Needs:   Node 24 (global fetch and WebSocket) and a Notaya window started with the debug port.
//          Throwaway vault only: it creates a NEW vault, so it must never be pointed at a real one.
import { readFileSync } from "node:fs";
const [port, pwFile] = process.argv.slice(2);
const password = readFileSync(pwFile, "utf8").trim();
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

const connectMain = () => connectLegacy(port);
try {
const m = await connectMain();
await sleep(1500);
const doc = (t) => JSON.stringify({ type: "doc", content: [{ type: "paragraph", content: [{ type: "text", text: t }] }] });
const check = (name, ok, extra = "") => console.log(`${ok ? "PASS" : "FAIL"}  ${name} ${extra}`);
const pageText = async () => {
  const tree = (await m.inv("list_notes")).ok;
  const p = tree?.pages?.find((x) => x.title === "R1");
  return p ? (await m.inv("get_page", { id: p.id })).ok?.text : "(no page)";
};

// A21: the first run opens an open vault by itself; give it a master password so it can lock.
await m.inv("vault_status");
console.log("turn security on:", JSON.stringify(await m.inv("enable_security", { password, keyfile: null, removeUnprotectedCopies: false })));
// The PC may have been idle for more than the 5-minute auto-lock: raise it at once (throwaway vault only).
{ const s = (await m.inv("get_settings")).ok; console.log("idle lock raised:", s ? JSON.stringify((await m.inv("save_settings", { settings: { ...s, idleLockMinutes: 180 } })).ok?.idleLockMinutes) : "settings unavailable (already locked?)"); }
await m.reload();
const section = await createNotebookSection(m);
const pg = await m.inv("create_page", { sectionId: section.id, title: "R1" });
await m.inv("save_page", { id: pg.ok.id, title: "R1", content: doc("ORIGINAL-TEXT"), text: "ORIGINAL-TEXT" });
await m.inv("lock_vault"); await sleep(3500);            // backup A (ORIGINAL)
console.log("unlock:", JSON.stringify(await m.inv("unlock_vault", { password, keyfile: null })));
await m.inv("save_page", { id: pg.ok.id, title: "R1", content: doc("CHANGED-AFTER-BACKUP"), text: "CHANGED-AFTER-BACKUP" });
await m.inv("lock_vault"); await sleep(3500);            // backup B (CHANGED)
const list = (await m.inv("list_backups")).ok;
console.log("backups listed (locked):", list?.map((b) => b.name + ":" + b.size).join(" | "));
check("list_backups works while locked, newest first", Array.isArray(list) && list.length >= 2 && list[0].modifiedMs >= list[1].modifiedMs);
const oldest = list[list.length - 1].name, newest = list[0].name;

console.log("unlock:", JSON.stringify(await m.inv("unlock_vault", { password, keyfile: null })));
check("live vault has CHANGED text", (await pageText()) === "CHANGED-AFTER-BACKUP", await pageText());
await m.inv("lock_vault"); await sleep(3500);

const abs = await m.inv("restore_vault", { source: "C:\\Windows\\win.ini", password, keyfile: null });
check("absolute path that was not picked is refused", !!abs.err, JSON.stringify(abs));
const unc = await m.inv("restore_vault", { source: "\\\\127.0.0.1\\c$\\x.clf", password, keyfile: null });
check("UNC path refused", !!unc.err, JSON.stringify(unc));
const trav = await m.inv("restore_vault", { source: "vault-..\\..\\vault.nota", password, keyfile: null });
check("path traversal name refused", !!trav.err, JSON.stringify(trav));

const wrong = await m.inv("restore_vault", { source: oldest, password: password.split("").reverse().join("") + "x", keyfile: null });
check("wrong password refused", !!wrong.err, JSON.stringify(wrong));
console.log("unlock:", JSON.stringify(await m.inv("unlock_vault", { password, keyfile: null })));
check("vault unchanged after the failed restore", (await pageText()) === "CHANGED-AFTER-BACKUP", await pageText());
await m.inv("lock_vault"); await sleep(3500);

const r1 = await m.inv("restore_vault", { source: oldest, password, keyfile: null });
console.log("restore (locked) result:", JSON.stringify(r1));
check("restore while locked succeeded and returned an undo file", !!r1.ok?.undoFile);
check("restored vault is open with the ORIGINAL text", (await pageText()) === "ORIGINAL-TEXT", await pageText());

const r2 = await m.inv("restore_vault", { source: newest, password, keyfile: null });
console.log("restore (unlocked) result:", JSON.stringify(r2));
check("restore while unlocked succeeded", !!r2.ok?.undoFile);
await sleep(1500);
check("second restored vault is open with the CHANGED text", (await pageText()) === "CHANGED-AFTER-BACKUP", await pageText());
const st = (await m.inv("vault_status")).ok;
check("vault is unlocked after restore", st?.unlocked === true);

} finally { await closeLegacyClients(); }
