import { connectLegacy, closeLegacyClients, createNotebookSection } from "./legacy-cdp.mjs";
// lockflow.mjs - real-exe test of "unsaved edits survive a lock or a window close".
// Purpose: types text into a page or sticky note, locks / closes at once (inside the save delay), unlocks,
//          and prints whether the typed text was saved ("page contains ...: true").
// Usage:   normally started by run-lockflow.ps1:  node lockflow.mjs <port> <phase> <scenario> <password-file>
//          <port> is the WebView2 debug port (9335) of a test copy of Notaya.exe;
//          <password-file> holds the throwaway passphrase (generated by the runner, never committed).
// Needs:   Node 24 (global fetch and WebSocket) and a Notaya window started with the debug port.
//          Throwaway vault only: phase "setup" creates a NEW vault, never point it at a real one.
//   phase "setup":  create the vault, a notebook, a page and a sticky note (window opens)
//   phase "type":   scenario page|sticky|close : type text, then lock/close at once
//   phase "check":  unlock and print whether the typed text was saved
import { readFileSync } from "node:fs";
import assert from "node:assert/strict";

const [port, phase, scenario = "page", pwFile] = process.argv.slice(2);
const password = readFileSync(pwFile, "utf8").trim();
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const connect = match => connectLegacy(port, match);

const isMain = (l) => l === "main";
const isSticky = (l) => String(l).startsWith("sticky-");
const TYPED = "FLUSHTEST-" + scenario;

try {
const main = await connect(isMain);
await sleep(1500);

if (phase === "setup") {
  // A21: the first run opens an open vault by itself; give it a master password so it can lock.
  await main.inv("vault_status");
  console.log("turn security on:", JSON.stringify(await main.inv("enable_security", { password, keyfile: null, removeUnprotectedCopies: false })));
  // The PC may have been idle for more than the 5-minute auto-lock: raise it at once (throwaway vault only).
  { const s = (await main.inv("get_settings")).ok; console.log("idle lock raised:", s ? JSON.stringify((await main.inv("save_settings", { settings: { ...s, idleLockMinutes: 180 } })).ok?.idleLockMinutes) : "settings unavailable (already locked?)"); }
  await main.reload();
  const sec = await createNotebookSection(main);
  const pg = await main.inv("create_page", { sectionId: sec.id, title: "Flush page" });
  console.log("page:", pg.ok?.id ? "created" : JSON.stringify(pg));
  const st = await main.inv("create_sticky", { open: true });
  console.log("sticky:", st.ok?.id ? "created" : JSON.stringify(st));
  await sleep(500);
  console.log("windows:", (await (await fetch(`http://127.0.0.1:${port}/json`)).json()).filter((x) => x.type === "page").map((x) => x.title).join(" | "));
} else if (phase === "type") {
  // open the page in the UI so its editor is mounted
  await main.reload();
  console.log("unlock:", JSON.stringify(await main.inv("unlock_vault", { password, keyfile: null })));
  await main.reload();
  const opened = await main.ev(`(() => { const s=[...document.querySelectorAll('aside span')].find(s=>s.textContent==='Flush page'); s?.click(); return !!s; })()`);
  assert.equal(opened, true, 'Flush page must be opened through the sidebar');
  console.log("open page:", opened);
  await sleep(1500);
  let sticky = null;
  if (scenario === "sticky") {
    sticky = await connect(isSticky);
    await sleep(800);
  }
  const target = scenario === "sticky" ? sticky : main;
  const typed = await target.ev(`(() => { const pm=document.querySelector('.ProseMirror'); if(!pm) return 'no editor'; pm.focus(); document.execCommand('insertText', false, ${JSON.stringify(TYPED)}); return pm.textContent; })()`);
  assert.ok(typeof typed === 'string' && typed.includes(TYPED), 'probe text must reach the editor');
  console.log("typed into editor:", JSON.stringify(typed));
  // lock or close at once, well inside the 350-500 ms save delay
  if (scenario === "close") {
    main.ev(`window.__TAURI_INTERNALS__.invoke('plugin:window|close', { label: 'main' }).catch(()=>{})`).catch(() => {});
  } else {
    main.ev(`(() => { const b=[...document.querySelectorAll('button')].find(b => b.textContent.trim()==='Lock'); if(!b) return 'no lock button'; b.click(); return 'clicked'; })()`).then((r) => console.log("lock click:", r)).catch(() => {});
  }
  await sleep(1500);
  if (scenario !== "close") {
    const v = await main.inv("vault_status");
    console.log("vault locked after click:", v.ok ? !v.ok.unlocked : JSON.stringify(v));
  }
  await sleep(2500);
} else if (phase === "check") {
  console.log("unlock:", JSON.stringify(await main.inv("unlock_vault", { password, keyfile: null })));
  const tree = (await main.inv("list_notes")).ok;
  const p = tree.pages.find((x) => x.title === "Flush page");
  const pg = (await main.inv("get_page", { id: p.id })).ok;
  const stk = (await main.inv("list_stickies")).ok?.[0];
  const sg = stk ? (await main.inv("get_sticky", { id: stk.id })).ok : null;
  const inPage = (pg?.text ?? "") + (pg?.content ?? "");
  const inSticky = (sg?.text ?? "") + (sg?.content ?? "");
  console.log(`page contains "${TYPED}":`, inPage.includes(TYPED));
  console.log(`sticky contains "${TYPED}":`, inSticky.includes(TYPED));
} else { throw Error('Unknown lockflow phase'); }
} finally { await closeLegacyClients(); }
