/// The Windows-1252 code of a character, if the standard fonts have it.
pub fn win_ansi(c: char) -> Option<u8> {
    const HIGH: [(char, u8); 27] = [
        ('\u{20AC}', 0x80), ('\u{201A}', 0x82), ('\u{0192}', 0x83), ('\u{201E}', 0x84), ('\u{2026}', 0x85), ('\u{2020}', 0x86), ('\u{2021}', 0x87),
        ('\u{02C6}', 0x88), ('\u{2030}', 0x89), ('\u{0160}', 0x8A), ('\u{2039}', 0x8B), ('\u{0152}', 0x8C), ('\u{017D}', 0x8E), ('\u{2018}', 0x91),
        ('\u{2019}', 0x92), ('\u{201C}', 0x93), ('\u{201D}', 0x94), ('\u{2022}', 0x95), ('\u{2013}', 0x96), ('\u{2014}', 0x97), ('\u{02DC}', 0x98),
        ('\u{2122}', 0x99), ('\u{0161}', 0x9A), ('\u{203A}', 0x9B), ('\u{0153}', 0x9C), ('\u{017E}', 0x9E), ('\u{0178}', 0x9F),
    ];
    match c as u32 {
        0x20..=0x7E | 0xA0..=0xFF => Some(c as u32 as u8),
        _ => HIGH.iter().find(|(h, _)| *h == c).map(|(_, b)| *b),
    }
}

/// A stand-in made of characters the fonts have, for a few common ones they lack.
pub fn fallback(c: char) -> Option<&'static str> {
    Some(match c {
        '→' | '⇒' | '➜' => "->",
        '←' | '⇐' => "<-",
        '↔' => "<->",
        '≤' => "<=",
        '≥' => ">=",
        '≠' => "!=",
        '≈' => "~",
        '✓' | '✔' | '☑' | '✅' => "[x]",
        '☐' => "[ ]",
        '✗' | '✘' | '❌' => "x",
        '\u{2032}' => "'",
        '\u{2033}' => "\"",
        '\u{2212}' | '\u{2010}' | '\u{2011}' => "-",
        '\u{2002}' | '\u{2003}' | '\u{2007}' | '\u{2009}' | '\u{200A}' | '\u{202F}' => " ",
        _ => return None,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_tables_match_known_widths() {
        let w = |t: &[u16; 224], c: char| t[win_ansi(c).unwrap() as usize - 32];
        assert_eq!(w(&HELVETICA, ' '), 278);
        assert_eq!(w(&HELVETICA, 'W'), 944);
        assert_eq!(w(&HELVETICA, 'i'), 222);
        assert_eq!(w(&HELVETICA_BOLD, 'i'), 278);
        assert_eq!(w(&HELVETICA, '€'), 556);
        assert_eq!(w(&HELVETICA, 'é'), 556);
        assert_eq!(win_ansi('“'), Some(0x93));
        assert_eq!(win_ansi('م'), None);
        assert_eq!(fallback('→'), Some("->"));
    }
}
