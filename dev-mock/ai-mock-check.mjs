// No additional packages: checks the mock command/event contract, not Rust security.
// Run with Node 24: node dev-mock/ai-mock-check.mjs
import assert from "node:assert/strict";
import { aiCommand, aiLock, aiMock } from "./ai.ts";
import { listen } from "./event.ts";
import { activityUpdate, aiErrorText, confirmRequest, pairingRequest, withStatus } from "../src/features/ai/contract.ts";

let checks = 0;
const eq = (name, value, expected) => { assert.deepEqual(value, expected, name); console.log(`ok ${++checks} ${name}`); };
const refuses = (name, fn, code) => { assert.throws(fn, (e) => e === code, name); console.log(`ok ${++checks} ${name}`); };
const call = (command, args = {}) => aiCommand(command, args);
const events = [];
const stop = await listen("items-changed", (event) => events.push(event.event));
aiMock.reset();
eq("default state is Off with 20-item confirmation", [aiMock.state().enabled, aiMock.state().bigChangeConfirm, aiMock.state().bigChangeItems], [false, true, 20]);
refuses("enabling needs ALLOW", () => call("ai_set_enabled", { enabled: true }), "not_confirmed");
call("ai_set_enabled", { enabled: true, confirmation: "ALLOW" });
const first = aiMock.pair("Writer");
call("ai_pair_answer", { id: first, allow: false });
eq("Deny creates no pairing", aiMock.state().pairings, []);
const expired = aiMock.pair("Expired", Date.now() - 1);
refuses("expired pairing cannot be allowed", () => call("ai_pair_answer", { id: expired, allow: true }), "pairing_refused");
call("ai_pair_answer", { id: expired, allow: false });
const writerRequest = aiMock.pair("Writer");
call("ai_pair_answer", { id: writerRequest, allow: true });
const writer = aiMock.state().pairings[0].id;
const readerRequest = aiMock.pair("Reader");
call("ai_pair_answer", { id: readerRequest, allow: true });
const reader = aiMock.state().pairings[1].id;
eq("new pairings have independent Look levels", aiMock.state().pairings.map((p) => p.level), ["look", "look"]);
eq("pairing result ids differ from broker request ids", writer !== writerRequest && reader !== readerRequest, true);
const beforeDuplicate = aiMock.state().pairings;
const duplicate = aiMock.pair("Writer");
eq("duplicate answer acknowledges only the broker", call("ai_pair_answer", { id: duplicate, allow: true }), null);
eq("duplicate pairing preserves every existing credential and level", aiMock.state().pairings, beforeDuplicate);
eq("duplicate failure stays pipe-only, without a client label", aiMock.bridgeErrors(), [{ code: "pairing_refused", message: "pairing_refused" }]);
eq("pairing refusal uses fixed plain copy", aiErrorText({ code: "pairing_refused", message: "PRIVATE_CLIENT_NAME" }), "The connection could not be paired. Check existing pairings in Settings and try again.");
eq("identified overload never echoes message or request id", aiErrorText({ id: 42, code: "rate_limited", message: "PRIVATE_NOTE_CONTENT" }), "Too many AI requests are waiting. Wait a moment, then try again.");
eq("unknown errors never echo arbitrary content", aiErrorText(new Error("PRIVATE_NOTE_CONTENT")), "The AI access change could not be saved. Try again.");
call("ai_set_level", { pairingId: writer, level: "full" });
eq("level updates only one pairing", aiMock.state().pairings.map((p) => p.level), ["full", "look"]);
refuses("unknown level is refused", () => call("ai_set_level", { pairingId: writer, level: "owner" }), "invalid");
call("ai_set_hidden", { notebookIds: ["n1", "n1"] });
eq("hidden notebook ids match C5's unchanged vector", aiMock.state().hiddenNotebooks, ["n1", "n1"]);
refuses("unknown hidden notebook is refused", () => call("ai_set_hidden", { notebookIds: ["missing"] }), "invalid");
call("ai_set_big_change", { enabled: false });
eq("big-change switch persists", aiMock.state().bigChangeConfirm, false);
call("ai_set_big_change", { enabled: true, items: 1 });
eq("optional big-change item threshold matches the core", aiMock.state().bigChangeItems, 1);
refuses("zero item threshold is refused", () => call("ai_set_big_change", { enabled: true, items: 0 }), "invalid");
refuses("oversized item threshold is refused", () => call("ai_set_big_change", { enabled: true, items: 501 }), "invalid");
const ask = aiMock.confirm("ask");
call("ai_confirm_answer", { id: ask, allow: true, word: null });
eq("Ask is resolved by its id", aiMock.state().confirmRequests, []);
const strong = aiMock.confirm("strong");
refuses("Strong refuses the wrong word", () => call("ai_confirm_answer", { id: strong, allow: true, word: "maple" }), "not_confirmed");
call("ai_confirm_answer", { id: strong, allow: true, word: "MAPLE-CEDAR" });
eq("Strong accepts the exact challenge", aiMock.state().confirmRequests, []);
const old = aiMock.confirm("ask", { expiresAt: Date.now() - 1 });
refuses("expired confirmation cannot allow", () => call("ai_confirm_answer", { id: old, allow: true }), "not_confirmed");
call("ai_confirm_answer", { id: old, allow: false });
aiMock.activity(writer, ["Plan"]);
aiMock.confirm("ask");
call("ai_pause");
eq("Stop clears activity and pending requests", [aiMock.state().paused, aiMock.state().activity, aiMock.state().confirmRequests], [true, [], []]);
call("ai_resume");
eq("Resume clears pause", aiMock.state().paused, false);
aiMock.confirm("ask");
aiLock(true);
eq("lock cancels all pending requests", aiMock.state().confirmRequests, []);
refuses("locked UI commands refuse", () => call("ai_get_status"), "The vault is locked.");
aiLock(false);
aiMock.fail("ai_set_level");
refuses("failed command leaves stored state intact", () => call("ai_set_level", { pairingId: writer, level: "edit" }), "invalid");
eq("failed level was not persisted", aiMock.state().pairings[0].level, "full");
aiMock.activity(writer);
call("ai_remove_pairing", { pairingId: writer });
eq("Remove clears just that pairing and its activity", [aiMock.state().pairings.map((p) => p.id), aiMock.state().activity], [[reader], []]);
call("ai_set_enabled", { enabled: false });
eq("Off closes mock access", aiMock.state().enabled, false);
const copy = call("ai_get_status");
copy.pairings.length = 0;
eq("a UI snapshot cannot mutate stored rules", aiMock.state().pairings.length, 1);
eq("UI pairings contain no tokens or hashes", Object.keys(aiMock.state().pairings[0]).sort(), ["created", "id", "lastUsed", "level", "name"]);
refuses("unknown commands fail instead of pretending success", () => call("ai_unknown"), "invalid");
eq("commands publish state invalidations", events.length > 0, true);
const count = events.length;
stop();
aiMock.reset();
eq("event listeners can be removed", events.length, count);
// Exercise C5's event-only DTOs and the display-state lifecycle without a browser.
const pairingEvents = [];
const confirmEvents = [];
const offPair = await listen("ai-pairing", ({ payload }) => pairingEvents.push(payload));
const offConfirm = await listen("ai-confirm", ({ payload }) => confirmEvents.push(payload));
call("ai_set_enabled", { enabled: true, confirmation: "ALLOW" });
const pairedRequest = aiMock.pair("Reader");
call("ai_pair_answer", { id: pairedRequest, allow: true });
const paired = aiMock.state().pairings[0].id;
const pending = aiMock.pair("Second writer");
eq("pairing uses C5 event envelope", pairingEvents.at(-1), { id: pending, kind: "pairing", details: { client: "Second writer" }, word: null });
eq("pairing event supplies a local display deadline", pairingRequest(pairingEvents.at(-1), 100).expiresAt, 300100);
aiMock.confirm("strong", { word: "RIVER-STONE" });
const event = confirmEvents.at(-1);
eq("confirmation uses C5 kind, item objects and random word", [event.kind, event.details.action, event.details.items[0], event.word], ["confirm", "page.trash", { id: "p1", title: "Plan" }, "RIVER-STONE"]);
const request = confirmRequest(event, 200);
eq("confirmation adapter preserves all titles and the exact challenge", [request.kind, request.word, request.items, request.expiresAt], ["strong", "RIVER-STONE", ["Plan", "Budget", "Notes"], 300200]);
eq("container confirmation uses the real trash action", confirmRequest({ ...event, details: { ...event.details, action: "notebook.trash" } }).summary, "move a notebook and its contents to the bin.");
eq("unrecognized action text is never echoed", confirmRequest({ ...event, details: { ...event.details, action: "PRIVATE_CONTENT" } }).summary, "make this change.");
const status = call("ai_get_status");
eq("status response has only C5 display fields", Object.keys(status).sort(), ["bigChangeConfirm", "bigChangeItems", "enabled", "hiddenNotebooks", "pairings", "paused"]);
let ui = { ...withStatus(null, status), pairingRequests: [pairingRequest(pairingEvents.at(-1), 100)], confirmRequests: [request] };
ui = activityUpdate(ui, { pairingId: paired, name: "Reader", at: 300, items: ["p1", "p2"] });
eq("activity uses C5 timestamp and target ids", ui.activity[0], { pairingId: paired, name: "Reader", lastActiveAt: 300, claims: ["p1", "p2"] });
eq("status polling and reopening retain newly received requests", [withStatus(ui, status).confirmRequests, withStatus({ ...ui, enabled: false }, status).confirmRequests, withStatus({ ...ui, paused: true }, status).confirmRequests], [[request], [request], [request]]);
eq("a new pairing preserves other pending dialogs", withStatus(ui, { ...status, pairings: [...status.pairings, { id: "new", name: "New", level: "look", created: 0, lastUsed: null }] }).pairingRequests.length, 1);
eq("a level change cancels confirms but retains pair requests", [withStatus(ui, { ...status, pairings: status.pairings.map((p) => ({ ...p, level: "edit" })) }).confirmRequests.length, withStatus(ui, { ...status, pairings: status.pairings.map((p) => ({ ...p, level: "edit" })) }).pairingRequests.length], [0, 1]);
eq("Stop clears event-only display state", [withStatus(ui, { ...status, paused: true }).confirmRequests, withStatus(ui, { ...status, paused: true }).activity], [[], []]);
eq("hidden notebook changes cancel requests", withStatus(ui, { ...status, hiddenNotebooks: ["n2"] }).pairingRequests, []);
refuses("retired fake-only command is refused", () => call("ai_get_state"), "invalid");
refuses("retired pairing command is refused", () => call("ai_pairing_answer", { id: pending, allow: true }), "invalid");
offPair(); offConfirm();
console.log(`ALL OK (${checks} checks; mock contract only)`);
